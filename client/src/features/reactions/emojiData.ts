function parseLine(line: string): EmojiEntry {
  const [emoji, name, kw = ''] = line.split('|');
  return { emoji, name, keywords: kw.split(/\s+/).filter(Boolean) };
}

export const EMOJI_GROUPS: EmojiGroup[] = RAW.map((g) => ({
  id: g.id,
  label: g.label,
  icon: g.icon,
  entries: g.lines.map(parseLine),
}));

export const ALL_EMOJI: EmojiEntry[] = EMOJI_GROUPS.flatMap((g) => g.entries);

/** Shortcode for an entry: lowercase name with spaces as underscores. */
export function shortcodeFor(entry: EmojiEntry): string {
  return entry.name.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');
}
